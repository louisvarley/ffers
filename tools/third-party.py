#!/usr/bin/env python3
"""Third-party licence inventory for the shipped executables (burndown release-4).

Reads `cargo metadata` for ffe-rs and ffe-launcher (Windows x64, normal and build
dependencies, as linked into the executables) and:

  python tools/third-party.py                 write docs/THIRD_PARTY.md
  python tools/third-party.py --check         fail if that file is stale, or a licence is
                                              neither permissive nor acknowledged below
  python tools/third-party.py --texts FILE    also write every dependency's licence and
                                              notice files (LICENSE*, COPYING*, NOTICE*)
                                              into FILE, for the package (not committed)

Needs `cargo` on PATH and the dependencies in the local registry (a normal build).
The inventory is not legal advice: it records what is linked and under what SPDX
expression, and flags what needs an owner decision.
"""
import argparse
import json
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = "x86_64-pc-windows-msvc"
SHIPPED = ("ffe-rs", "ffe-launcher")

PERMISSIVE = {
    "MIT", "Apache-2.0", "Unicode-3.0", "Unlicense", "Zlib", "BSD-2-Clause", "BSD-3-Clause",
    "BSL-1.0", "CC0-1.0", "ISC", "0BSD", "OFL-1.1", "Ubuntu-font-1.0",
}
# Licences that need an owner decision. A crate may only use one if it is named here;
# anything else with such a licence, or with none, fails --check.
ACKNOWLEDGED = {
    "oxisynth": "LGPL-2.1",
    "oxisynth-chorus": "LGPL-2.1",
    "oxisynth-reverb": "LGPL-2.1",
}
DOC = ROOT / "docs" / "THIRD_PARTY.md"

BUNDLED = """\
## Bundled data

| Item | Where | Terms |
|---|---|---|
| GeneralUser GS v2.0.3 SoundFont (32 MB) | `crates/ffe-audio/assets/soundfont/GeneralUser-GS.sf2`, compiled into the executable with `include_bytes!` (`crates/ffe-audio/src/render.rs`); licence text beside it | Free for use in software projects and to modify or repackage. The author states he cannot be certain where every sample came from, though none came from commercial banks; see the licence file. Ship that file with the package. |
| Launcher icon and background | `crates/ffe-launcher/assets/` | Project assets. |

No original game data, music, videos or generated caches are bundled; `tools/package.ps1`
refuses to build a package that contains any.
"""


def metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET],
        cwd=ROOT, capture_output=True, check=True, text=True, encoding="utf-8",
    ).stdout
    return json.loads(out)


def linked(meta):
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    stack = [p["id"] for p in meta["packages"] if p["name"] in SHIPPED]
    seen = set()
    while stack:
        ident = stack.pop()
        if ident in seen:
            continue
        seen.add(ident)
        for dep in nodes[ident]["deps"]:
            if any(kind.get("kind") in (None, "build") for kind in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    return sorted(
        (packages[i] for i in seen if packages[i]["source"] is not None),
        key=lambda p: (p["name"], p["version"]),
    )


def tokens(expression):
    return {t for t in re.split(r"[\s()/]+|AND|OR|WITH", expression or "") if t}


def classify(package):
    """'ok', 'acknowledged' or a problem string."""
    expression = package["license"]
    if not expression:
        return "has no licence field"
    found = tokens(expression)
    if found & PERMISSIVE and not any(t.startswith(("LGPL", "GPL", "AGPL", "MPL")) for t in found):
        unknown = found - PERMISSIVE
        return "ok" if not unknown else f"unrecognised licence term(s) {sorted(unknown)}"
    if ACKNOWLEDGED.get(package["name"]) == expression:
        return "acknowledged"
    return f"licence {expression} needs an owner decision"


def render(packages):
    groups = defaultdict(list)
    for package in packages:
        groups[package["license"] or "NONE"].append(f"{package['name']} {package['version']}")
    lines = [
        "# Third-party software",
        "",
        "Generated by `python tools/third-party.py`; do not edit by hand. It lists the Rust crates",
        f"linked into `{'` and `'.join(SHIPPED)}` for Windows x64, with their SPDX licence",
        "expression from each crate's manifest. Full licence and notice texts for a package come",
        "from `python tools/third-party.py --texts FILE` (run by `tools/package.ps1`).",
        "",
        f"{len(packages)} third-party crates.",
        "",
        "## Acknowledged by the owner",
        "",
    ]
    flagged = [p for p in packages if classify(p) != "ok"]
    if flagged:
        lines += [
            "| Crate | Licence | Why it matters |",
            "|---|---|---|",
        ]
        for p in flagged:
            lines.append(
                f"| `{p['name']}` {p['version']} | {p['license'] or 'none'} | "
                + ("LGPL-2.1, linked statically into the executable. The owner approved shipping it "
                   "(2026-11-22); `docs/LGPL.md` is the relinking arrangement (public source, pinned "
                   "dependencies, a build recipe) that every package carries, with the LGPL text in "
                   "`THIRD_PARTY_LICENSES.txt`."
                   if (p["license"] or "").startswith("LGPL") else "Check before release.")
                + " |"
            )
    else:
        lines.append("None.")
    lines += ["", BUNDLED, "## Crates by licence", ""]
    for expression in sorted(groups, key=lambda k: (-len(groups[k]), k)):
        lines.append(f"### {expression} ({len(groups[expression])})")
        lines.append("")
        lines.append(", ".join(f"`{name}`" for name in groups[expression]))
        lines.append("")
    return "\n".join(lines)


def write_texts(packages, path):
    patterns = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE)", re.IGNORECASE)
    with open(path, "w", encoding="utf-8", newline="\n") as out:
        out.write("Licence and notice files of the third-party crates linked into the executables.\n")
        for package in packages:
            folder = Path(package["manifest_path"]).parent
            files = sorted(f for f in folder.iterdir() if f.is_file() and patterns.match(f.name))
            out.write(f"\n{'=' * 78}\n{package['name']} {package['version']}  ({package['license']})\n{'=' * 78}\n")
            if not files:
                out.write("(no licence file in the published crate; see its repository)\n")
            for file in files:
                out.write(f"\n--- {file.name} ---\n")
                out.write(file.read_text(encoding="utf-8", errors="replace"))
                out.write("\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--texts", type=Path)
    args = parser.parse_args()
    packages = linked(metadata())
    text = render(packages)
    if args.texts:
        write_texts(packages, args.texts)
    if args.check:
        problems = [f"{p['name']} {p['version']}: {classify(p)}" for p in packages
                    if classify(p) not in ("ok", "acknowledged")]
        current = DOC.read_text(encoding="utf-8").replace("\r\n", "\n") if DOC.exists() else ""
        if current != text.replace("\r\n", "\n"):
            problems.append("docs/THIRD_PARTY.md is stale; run python tools/third-party.py")
        if problems:
            print("third-party check failed:", file=sys.stderr)
            for problem in problems:
                print("  - " + problem, file=sys.stderr)
            return 1
        print(f"third-party check passed: {len(packages)} crates, "
              f"{sum(classify(p) == 'acknowledged' for p in packages)} acknowledged")
        return 0
    DOC.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {DOC.relative_to(ROOT)} ({len(packages)} crates)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
